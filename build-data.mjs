// Turn the Open-Meteo responses in data/ into the tables the page renders.
// Every number is taken from the API payloads; nothing here is synthesised.
import { readFileSync, writeFileSync } from 'node:fs'

const DISTRICTS = [
  { id: 'tianhe', name: '天河', street: '体育西路', file: 'data/gz-tianhe.json' },
  { id: 'yuexiu', name: '越秀', street: '环市东路', file: 'data/gz-yuexiu.json' },
  { id: 'haizhu', name: '海珠', street: '江南大道', file: 'data/gz-haizhu.json' },
]

const WET = 0.05 // mm in a 15-minute cell, counted as rain

const hhmm = (iso) => iso.slice(11, 16)
const toMs = (iso) => Date.parse(iso + ':00+08:00') // Asia/Shanghai, no DST
const fromMs = (ms) => new Date(ms + 8 * 3600 * 1000).toISOString().slice(0, 16) // wall clock

function level(mm) {
  if (mm <= 0) return 'dry'
  if (mm <= 0.5) return 'light'
  if (mm <= 2.5) return 'mid'
  if (mm <= 8) return 'heavy'
  return 'storm'
}
const LEVEL_WORD = { dry: '无雨', light: '小雨', mid: '中雨', heavy: '大雨', storm: '暴雨' }

function buildDistrict(d) {
  const raw = JSON.parse(readFileSync(d.file, 'utf8'))
  const t = raw.minutely_15.time
  const p = raw.minutely_15.precipitation
  const nowMs = Date.now()
  const startIdx = Math.max(0, t.findIndex((x) => toMs(x) >= nowMs - 15 * 60 * 1000))

  const cells = []
  for (let i = startIdx; i < Math.min(t.length, startIdx + 12 * 4 + 1); i++) {
    cells.push({ time: t[i], mm: Number(p[i] ?? 0) })
  }

  // Merge the cells into runs of dry or wet weather.
  const windows = []
  for (const c of cells) {
    const wet = c.mm >= WET
    const last = windows[windows.length - 1]
    if (last && last.wet === wet) {
      last.end = c.time
      last.cells += 1
      last.peak = Math.max(last.peak, c.mm)
      last.total += c.mm
    } else {
      windows.push({ wet, start: c.time, end: c.time, cells: 1, peak: c.mm, total: c.mm })
    }
  }
  for (const w of windows) {
    w.minutes = w.cells * 15
    w.from = hhmm(w.start)
    w.to = hhmm(fromMs(toMs(w.end) + 15 * 60 * 1000))
    w.rate = Number((w.peak * 4).toFixed(1)) // 15-minute depth -> mm/h
    w.total = Number(w.total.toFixed(1))
    w.level = level(w.rate)
    w.word = LEVEL_WORD[w.level]
  }

  const hourly = raw.hourly
  const h0 = Math.max(0, hourly.time.findIndex((x) => toMs(x) >= nowMs - 60 * 60 * 1000))
  const hours = []
  for (let i = h0; i < Math.min(hourly.time.length, h0 + 10); i++) {
    const mm = Number(hourly.precipitation[i] ?? 0)
    hours.push({
      time: hhmm(hourly.time[i]),
      mm: Number(mm.toFixed(1)),
      prob: hourly.precipitation_probability[i],
      wind: Math.round(hourly.wind_speed_10m[i]),
      temp: hourly.temperature_2m[i],
      level: level(mm),
      word: LEVEL_WORD[level(mm)],
    })
  }

  const nextRain = windows.find((w) => w.wet)

  return {
    id: d.id,
    name: d.name,
    street: d.street,
    updated: hhmm(hourly.time[h0]) + ':00',
    now: {
      temp: hourly.temperature_2m[h0],
      humidity: hourly.relative_humidity_2m[h0],
      wind: Math.round(hourly.wind_speed_10m[h0]),
      prob: hourly.precipitation_probability[h0],
      level: level(hours[0].mm),
      word: LEVEL_WORD[level(hours[0].mm)],
    },
    nextRain: nextRain
      ? { from: nextRain.from, to: nextRain.to, minutes: nextRain.minutes, rate: nextRain.rate, total: nextRain.total, word: nextRain.word }
      : null,
    windows: windows.slice(0, 5),
    hours,
    cells: cells.map((c) => ({ time: hhmm(c.time), mm: Number(c.mm.toFixed(2)) })),
  }
}

const out = {
  generated: new Date().toISOString(),
  source: 'Open-Meteo · minutely_15 · Asia/Shanghai',
  districts: DISTRICTS.map(buildDistrict),
}

writeFileSync('data/app-data.json', JSON.stringify(out, null, 1))
writeFileSync(
  'app-data.js',
  '// generated by build-data.mjs from the Open-Meteo responses in data/ — do not hand-edit\nwindow.WX = ' +
    JSON.stringify(out) +
    '\n',
)

for (const d of out.districts) {
  console.log(`\n${d.name} ${d.street} · 更新 ${d.updated} · ${d.now.temp}°C 湿度${d.now.humidity}% 风${d.now.wind}km/h`)
  console.log('  下一班雨:', d.nextRain ? `${d.nextRain.from}–${d.nextRain.to} ${d.nextRain.word} ${d.nextRain.rate}mm/h · ${d.nextRain.minutes}分钟` : '12 小时内无雨')
  console.log('  窗口:', d.windows.map((w) => `${w.word}${w.from}-${w.to}`).join('  '))
  console.log('  逐时:', d.hours.map((h) => `${h.time} ${h.mm}mm`).join('  '))
}
